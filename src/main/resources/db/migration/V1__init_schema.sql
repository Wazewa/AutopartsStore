CREATE TABLE IF NOT EXISTS Customer (
    customer_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(30) NOT NULL,
    surname VARCHAR(30) NOT NULL,
    patronymic VARCHAR(30) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(256) NOT NULL,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    phone VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS Admin (
    admin_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(30) NOT NULL,
    surname VARCHAR(30) NOT NULL,
    patronymic VARCHAR(30) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(256) NOT NULL,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    access_level INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS Category (
    category_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name_category VARCHAR(30) NOT NULL,
    description_category TEXT
);

CREATE TABLE IF NOT EXISTS Product (
    product_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    category_id INTEGER REFERENCES Category(category_id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    price DECIMAL(10, 2) NOT NULL CHECK (price >= 0),
    article VARCHAR(100),
    quantity INTEGER NOT NULL CHECK (quantity >= 0),
    image_url VARCHAR(1024),
    brand VARCHAR(100),
    comment TEXT
);

CREATE TABLE IF NOT EXISTS Compatibility (
    compatibility_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER REFERENCES Product(product_id) ON DELETE CASCADE NOT NULL,
    brand VARCHAR(100),
    model VARCHAR(100),
    year_start INTEGER CHECK (year_start >= 1950),
    year_end INTEGER CHECK (year_start <= year_end)
);

CREATE TABLE IF NOT EXISTS Cart (
    cart_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER REFERENCES Customer(customer_id) ON DELETE CASCADE NOT NULL UNIQUE,
    created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS Cart_Product (
    cart_product_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    cart_id INTEGER REFERENCES Cart(cart_id) ON DELETE CASCADE NOT NULL,
    product_id INTEGER REFERENCES Product(product_id) ON DELETE CASCADE NOT NULL,
    price_add_at DECIMAL(10, 2) NOT NULL CHECK (price_add_at >= 0),
    quantity INTEGER NOT NULL CHECK (quantity >= 0)
);

CREATE TABLE IF NOT EXISTS Orders (
    order_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER REFERENCES Customer(customer_id) NOT NULL,
    processed_by_admin_id INTEGER REFERENCES Admin(admin_id) ON DELETE CASCADE,
    order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    pay_method VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS Order_Product (
    order_product_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    order_id INTEGER REFERENCES Orders(order_id) ON DELETE CASCADE NOT NULL,
    product_id INTEGER REFERENCES Product(product_id) ON DELETE CASCADE NOT NULL,
    price_add_at DECIMAL(10, 2) NOT NULL CHECK (price_add_at >= 0),
    quantity INTEGER NOT NULL CHECK (quantity >= 0)
);

CREATE TABLE IF NOT EXISTS Event (
    event_id INTEGER PRIMARY KEY NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    customer_id INTEGER REFERENCES Customer(customer_id),
    event_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    event_type VARCHAR(128) NOT NULL,
    session_id INTEGER NOT NULL CHECK (session_id > 0)
)
